#!/bin/bash
# diag_regs2.sh — Complete FPGA register dump with correct mapping
BAR0=0xf0200000
echo "=== FPGA Register Dump (Phase 11) ==="
echo ""
echo "--- Video Registers (0x40-0x7C) ---"
echo "TPG_STATUS      (0x40): $(busybox devmem $((BAR0+0x40)))"
echo "WIDTH           (0x44): $(busybox devmem $((BAR0+0x44)))"
echo "HEIGHT          (0x48): $(busybox devmem $((BAR0+0x48)))"
echo "PIXEL_FORMAT    (0x4C): $(busybox devmem $((BAR0+0x4C)))"
echo "FRAME_COUNT     (0x50): $(busybox devmem $((BAR0+0x50)))"
echo "FPS_CONFIG      (0x54): $(busybox devmem $((BAR0+0x54)))"
echo "BYTES_PER_FRAME (0x58): $(busybox devmem $((BAR0+0x58)))"
echo "VERSION         (0x5C): $(busybox devmem $((BAR0+0x5C)))"
echo "CTRL            (0x60): $(busybox devmem $((BAR0+0x60)))"
echo "PADDED_BYTES    (0x64): $(busybox devmem $((BAR0+0x64)))"
echo "DROP_COUNT      (0x68): $(busybox devmem $((BAR0+0x68)))"
echo "PATTERN_SEL     (0x6C): $(busybox devmem $((BAR0+0x6C)))"
echo "DELIVERED_COUNT (0x70): $(busybox devmem $((BAR0+0x70)))"
echo "DBG_STATE       (0x74): $(busybox devmem $((BAR0+0x74)))"
echo "DBG_PIX_CNT     (0x78): $(busybox devmem $((BAR0+0x78)))"
echo "DBG_DMA_BEAT    (0x7C): $(busybox devmem $((BAR0+0x7C)))"
echo ""
echo "--- Camera Registers (0x80-0x98) ---"
echo "SOURCE_SEL      (0x80): $(busybox devmem $((BAR0+0x80)))"
echo "CAM_STATUS      (0x84): $(busybox devmem $((BAR0+0x84)))"
echo "CAM_FRAME_COUNT (0x88): $(busybox devmem $((BAR0+0x88)))"
echo "CAM_ERROR       (0x8C): $(busybox devmem $((BAR0+0x8C)))"
echo "CAM_MODE        (0x90): $(busybox devmem $((BAR0+0x90)))"
echo "DROP_DETECT_CNT (0x94): $(busybox devmem $((BAR0+0x94)))"
echo "AE_GAIN         (0x98): $(busybox devmem $((BAR0+0x98)))"
echo ""
echo "--- Decode DBG_STATE ---"
DBG=$(busybox devmem $((BAR0+0x74)))
DBG_DEC=$((DBG))
echo "  [0]  user_link_up    : $(( (DBG_DEC >> 0) & 1 ))"
echo "  [1]  reg_enable      : $(( (DBG_DEC >> 1) & 1 ))"
echo "  [2]  tready_ever     : $(( (DBG_DEC >> 2) & 1 ))"
echo "  [3]  vid_frame_last  : $(( (DBG_DEC >> 3) & 1 ))"
echo "  [4]  mipi_clk_present: $(( (DBG_DEC >> 4) & 1 ))"
echo "  [5]  (tpg_enable)    : $(( (DBG_DEC >> 5) & 1 ))"
echo "  [6]  cam_enable      : $(( (DBG_DEC >> 6) & 1 ))"
echo "  [7]  vid_tvalid      : $(( (DBG_DEC >> 7) & 1 ))"
echo "  [8]  c2h_tready      : $(( (DBG_DEC >> 8) & 1 ))"
echo "  [9]  cam_sof_seen    : $(( (DBG_DEC >> 9) & 1 ))"
echo "  [10] cam_i2c_done    : $(( (DBG_DEC >> 10) & 1 ))"
echo "  [11] source=Camera   : $(( (DBG_DEC >> 11) & 1 ))"
echo ""
echo "--- Decode CAM_ERROR (actual resolution) ---"
CAM_ERR=$(busybox devmem $((BAR0+0x8C)))
CAM_ERR_DEC=$((CAM_ERR))
echo "  Active Width : $(( (CAM_ERR_DEC >> 16) & 0x1FFF ))"
echo "  Active Height: $(( CAM_ERR_DEC & 0x1FFF ))"
